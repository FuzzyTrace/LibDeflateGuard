-- Measured, not assumed. With the JIT on, a delta on this workload moves by
-- more between two runs of this file than the within-run spread it reports:
-- the two modules are near-identical 4000-line copies sharing one trace
-- cache, and which traces survive a run is not the same twice. With -joff the
-- same shapes repeat to a point or two. That is also the interpreter proxy
-- every number this repository has published was taken on, so it is the same
-- recommendation twice over rather than a preference.
