-- The six migration-relevant paths.
io.write("\n## Migration paths, \"addon\" policy on this module\n\n")
local floor_notes = {}
if reference_api then
  io.write(("%-38s %6s %10s %10s %9s %8s\n"):format("Path", "calls", "this us",
                                                    "ref us", "delta", "spread"))
  io.write(string.rep("-", 86), "\n")
  local alloc_rows = {}
  for _, shape in ipairs(migration_shapes) do
    local measured = Measure(shape, {guard_api, reference_api})
    local mine, theirs, ratio = measured[1], measured[2], measured.ratio
    local delta = ratio.median - 1
    io.write(("%-38s %6d %10.2f %10.2f %9s %8s\n"):format(shape.name,
                                                          measured.calls,
                                                          mine.median * 1e6,
                                                          theirs.median * 1e6,
                                                          FormatDelta(delta),
                                                          FormatSpread(
                                                            ratio.spread)))
    -- Said in words, not left for the reader to work out from two columns.
    if math.abs(delta) <= ratio.spread then
      floor_notes[#floor_notes + 1] =
        ("%s: %s is inside the %s spread of the comparison, report it as about flat"):format(
          shape.name, FormatDelta(delta), FormatSpread(ratio.spread))
    end
    alloc_rows[#alloc_rows + 1] = {
      name = shape.name,
      mine = mine.alloc,
      theirs = theirs.alloc,
      delta = theirs.alloc > 0 and (mine.alloc / theirs.alloc - 1) or 0
    }
  end

  io.write("\n## Allocation per call\n\n")
  io.write(
    ("%-38s %14s %14s %8s\n"):format("Path", "this", "reference", "delta"))
  io.write(("%s\n"):format(string.rep("-", 78)))
  for _, row in ipairs(alloc_rows) do
    io.write(("%-38s %14s %14s %8s\n"):format(row.name, FormatBytes(row.mine),
                                              FormatBytes(row.theirs),
                                              FormatDelta(row.delta)))
  end
else
  io.write(("%-38s %6s %10s %8s %14s\n"):format("Path", "calls", "us/call",
                                                "spread", "alloc/call"))
  io.write(("%s\n"):format(string.rep("-", 80)))
  for _, shape in ipairs(migration_shapes) do
    local measured = Measure(shape, {guard_api})
    local mine = measured[1]
    io.write(("%-38s %6d %10.2f %8s %14s\n"):format(shape.name, measured.calls,
                                                    mine.median * 1e6,
                                                    FormatSpread(mine.spread),
                                                    FormatBytes(mine.alloc)))
  end
end

for _, note in ipairs(floor_notes) do io.write("# ", note, "\n") end

-- The worst work each preset accepts, which is what sizes a policy. Run
-- against this module only: a reference module has no policy to saturate.
io.write("\n## Saturation, worst accepted work per preset\n\n")
io.write(("%-10s %-12s %10s %10s %10s %8s %12s\n"):format("preset", "shape",
                                                          "input", "decoded",
                                                          "ms/call", "spread",
                                                          "alloc/call"))
io.write(("%s\n"):format(string.rep("-", 78)))
for _, shape in ipairs(saturation_shapes) do
  local measured = Measure(shape, {shape.api})
  local mine = measured[1]
  io.write(("%-10s %-12s %10s %10s %10.1f %8s %12s\n"):format(shape.preset,
                                                              shape.shape,
                                                              FormatBytes(
                                                                #shape.input),
                                                              FormatBytes(
                                                                shape.decoded_bytes),
                                                              mine.median * 1e3,
                                                              FormatSpread(
                                                                mine.spread),
                                                              FormatBytes(
                                                                mine.alloc)))
end

